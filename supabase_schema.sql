create table if not exists public.fingerprints (
  id bigint generated by default as identity primary key,
  customer_id text not null,
  fingerprint text not null,
  algorithm text not null check (algorithm in ('SHA-256', 'SHA-512')),
  captured_at timestamptz not null,
  source text not null,
  integrity_valid boolean not null default true,
  media_id text,
  created_at timestamptz not null default now()
);

alter table public.fingerprints add column if not exists media_id text;

alter table public.fingerprints add column if not exists customer_id text;
update public.fingerprints set customer_id = 'legacy-customer' where customer_id is null;
alter table public.fingerprints alter column customer_id set not null;

create index if not exists fingerprints_customer_id_idx on public.fingerprints (customer_id);

create table if not exists public.live_fingerprints (
  id bigint generated by default as identity primary key,
  customer_id text not null,
  fingerprint text not null,
  algorithm text not null check (algorithm in ('SHA-256', 'SHA-512')),
  captured_at timestamptz not null,
  source text not null
);

create index if not exists live_fingerprints_customer_id_idx on public.live_fingerprints (customer_id);

-- Idempotent retries from the offline outbox: event_id is a client UUID, seq the client sequence number.
alter table public.live_fingerprints add column if not exists event_id text;
alter table public.live_fingerprints add column if not exists seq bigint;
create unique index if not exists live_fingerprints_event_idx on public.live_fingerprints (customer_id, event_id);

create table if not exists public.media_files (
  media_id text primary key,
  customer_id text not null,
  filename text not null,
  media_type text not null,
  stored_path text not null,
  uploaded_at timestamptz not null,
  size_bytes bigint not null,
  fingerprint_count integer not null,
  file_sha256 text not null,
  content_base64 text not null,
  reuploaded boolean not null default false,
  duplicate_upload boolean not null default false,
  overlap_fingerprints text not null default '[]',
  overlap_media_ids text not null default '[]',
  fingerprint_manifest text not null default '[]'
);

alter table public.media_files add column if not exists file_sha256 text;
alter table public.media_files add column if not exists content_base64 text;
alter table public.media_files add column if not exists reuploaded boolean;
alter table public.media_files add column if not exists duplicate_upload boolean;
alter table public.media_files add column if not exists overlap_fingerprints text;
alter table public.media_files add column if not exists overlap_media_ids text;
alter table public.media_files add column if not exists fingerprint_manifest text;
update public.media_files set file_sha256 = '' where file_sha256 is null;
update public.media_files set content_base64 = '' where content_base64 is null;
update public.media_files set reuploaded = false where reuploaded is null;
update public.media_files set duplicate_upload = false where duplicate_upload is null;
update public.media_files set overlap_fingerprints = '[]' where overlap_fingerprints is null;
update public.media_files set overlap_media_ids = '[]' where overlap_media_ids is null;
update public.media_files set fingerprint_manifest = '[]' where fingerprint_manifest is null;
update public.media_files m
set fingerprint_manifest = coalesce((
  select json_agg(f.fingerprint order by f.id)::text
  from public.fingerprints f
  where f.media_id = m.media_id
), '[]')
where m.fingerprint_manifest = '[]';
alter table public.media_files alter column file_sha256 set not null;
alter table public.media_files alter column content_base64 set not null;
alter table public.media_files alter column reuploaded set not null;
alter table public.media_files alter column duplicate_upload set not null;
alter table public.media_files alter column overlap_fingerprints set not null;
alter table public.media_files alter column overlap_media_ids set not null;
alter table public.media_files alter column fingerprint_manifest set not null;

create index if not exists media_files_customer_id_idx on public.media_files (customer_id);

alter table public.fingerprints enable row level security;
alter table public.media_files enable row level security;
alter table public.live_fingerprints enable row level security;

drop policy if exists "service role can manage fingerprints" on public.fingerprints;
create policy "service role can manage fingerprints"
  on public.fingerprints for all
  using (auth.role() = 'service_role')
  with check (auth.role() = 'service_role');

drop policy if exists "service role can manage media files" on public.media_files;
create policy "service role can manage media files"
  on public.media_files for all
  using (auth.role() = 'service_role')
  with check (auth.role() = 'service_role');

drop policy if exists "service role can manage live fingerprints" on public.live_fingerprints;
create policy "service role can manage live fingerprints"
  on public.live_fingerprints for all
  using (auth.role() = 'service_role')
  with check (auth.role() = 'service_role');